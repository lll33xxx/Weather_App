    /**
     * 根据城市名获取经纬度 [经度, 纬度]
     * 支持直接匹配、去后缀匹配、加"市"匹配
     * @return [lon, lat] 或 null
     */
    public static double[] getCoord(String cityName) {
        if (cityName == null || cityName.isEmpty()) return null;
        // 1. 直接匹配
        if (COORDS.containsKey(cityName)) return COORDS.get(cityName);
        // 2. 去行政后缀后匹配
        String core = stripSuffix(cityName);
        if (core != null && COORDS.containsKey(core)) return COORDS.get(core);
        // 3. 加"市"匹配
        if (COORDS.containsKey(cityName + "市")) return COORDS.get(cityName + "市");
        // 4. 核心名加"市"
        if (core != null && COORDS.containsKey(core + "市")) return COORDS.get(core + "市");
        return null;
    }

    /**
     * 判断城市是否在支持列表中
     */
    public static boolean supports(String cityName) {
        return getCoord(cityName) != null;
    }

    /**
     * 去除行政后缀
     */
    private static String stripSuffix(String name) {
        String[] suffixes = {"特别行政区", "土家族苗族自治州", "壮族苗族自治州", "哈尼族彝族自治州",
                "藏族羌族自治州", "傣族景颇族自治州", "傈僳族自治州", "苗族侗族自治州",
                "布依族苗族自治州", "回族自治州", "蒙古族自治州", "哈萨克自治州",
                "柯尔克孜自治州", "彝族自治州", "白族自治州", "藏族自治州",
                "朝鲜族自治州", "傣族自治州", "自治州", "地区", "林区", "省", "盟", "县", "市"};
        for (String s : suffixes) {
            if (name.endsWith(s) && name.length() > s.length()) {
                return name.substring(0, name.length() - s.length());
            }
        }
        return name;
    }
