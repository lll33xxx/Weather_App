export const getProvinceCenter = (provinceName) => {
  if (!provinceName) return null
  if (provinceCenters[provinceName]) return provinceCenters[provinceName]
  const stripped = provinceName.replace(/(省|市|自治区|特别行政区|壮族|回族|维吾尔|藏族)$/, '')
  if (provinceCenters[stripped]) return provinceCenters[stripped]
  const suffixes = ['省', '市', '自治区', '特别行政区']
  for (const suf of suffixes) {
    if (provinceCenters[stripped + suf]) return provinceCenters[stripped + suf]
  }
  return null
}

/**
 * 根据城市名获取经纬度
 * 支持完整行政名称（如"临夏回族自治州"、"北京市"、"香港特别行政区"）
 * @param {string} cityName - 城市名
 * @returns {[number, number]|null} [经度, 纬度] 或 null
 */
export const getCityCoord = (cityName) => {
  if (!cityName) return null
  // 1. 直接匹配
  if (cityCoords[cityName]) return cityCoords[cityName]
  // 2. 去除行政后缀后匹配
  const coreName = stripSuffix(cityName)
  if (coreName && cityCoords[coreName]) return cityCoords[coreName]
  // 3. 加"市"后缀匹配
  if (cityCoords[cityName + '市']) return cityCoords[cityName + '市']
  // 4. 核心名加"市"匹配
  if (coreName && cityCoords[coreName + '市']) return cityCoords[coreName + '市']
  return null
}
